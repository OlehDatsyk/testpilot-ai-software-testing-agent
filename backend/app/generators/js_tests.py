"""Rule-based Vitest generation for exported JavaScript / TypeScript functions.

Grounded strategies only:
* ``export``  – the exported symbol exists and is a function
* ``example`` – ``@example fn(args) // => value`` lines in JSDoc become assertions
* ``guard``   – ``if (param <op> literal) throw new X`` becomes a toThrow test

Generated test files live in ``testpilot_generated/`` and use Vitest globals
(no import from 'vitest' is required; the runner enables ``globals``).
"""
from __future__ import annotations

import re

from app.analysis.static_js import extract_js_exports, strip_comments_and_strings
from app.generators.python_tests import Proposal

JSDOC_EXAMPLE = re.compile(r"@example\s+([A-Za-z_$][\w$]*\(.*?\))\s*//\s*=>\s*(.+)$", re.M)
GUARD = re.compile(
    r"if\s*\(\s*([A-Za-z_$][\w$]*)\s*(===|==|<=|>=|<|>)\s*(-?\d+(?:\.\d+)?)\s*\)\s*\{?\s*throw\s+new\s+([A-Za-z_$][\w$]*)"
)
EMPTY_GUARD = re.compile(
    r"if\s*\(\s*(?:!\s*([A-Za-z_$][\w$]*)\s*\|\|\s*)?([A-Za-z_$][\w$]*)\.length\s*===?\s*0\s*\)\s*\{?\s*throw\s+new\s+([A-Za-z_$][\w$]*)"
)
NAME_HINT_VALUES = [
    (re.compile(r"(items|values|numbers|list|arr|array|data|prices|scores)$", re.I), "[1, 2, 3]"),
    (re.compile(r"(name|text|str|s|label|title|message|email|code)$", re.I), "'abc'"),
    (re.compile(r"(rate|ratio|percent|discount)$", re.I), "0.1"),
]


def _placeholder(param: str) -> str:
    for pat, val in NAME_HINT_VALUES:
        if pat.search(param):
            return val
    return "1"


def _safe(s: str) -> str:
    return re.sub(r"\W+", "_", s).strip("_").lower()[:50]


def generate_for_file(rel: str, source: str, *, max_per_function: int = 3) -> list[Proposal]:
    if rel.endswith(".d.ts"):
        return []
    stripped = strip_comments_and_strings(source)
    exports = [e for e in extract_js_exports(stripped) if e["kind"] == "function"]
    if not exports:
        return []
    import_path = "../" + rel
    out: list[Proposal] = []
    names = ", ".join(e["name"] for e in exports)
    out.append(Proposal(
        name=f"exports functions from {rel}",
        description=f"{rel} exports the functions {names}.",
        target=rel, target_file=rel, category="unit",
        expected_behaviour=f"Each of [{names}] is exported and is a function.",
        code=(f"// Generated by TestPilot AI — review before approving.\nimport * as mod from '{import_path}';\n\n"
              f"describe('{rel} exports', () => {{\n"
              + "".join(f"  it('exports {e['name']}', () => {{\n    expect(typeof mod.{e['name']}).toBe('function');\n  }});\n"
                        for e in exports)
              + "});\n"),
        rationale="Baseline smoke test: confirms the module loads and its public API is present.",
        strategy="export", source_files=[rel]))

    for e in exports:
        fn, params = e["name"], e["params"]
        count = 0
        # Locate the function body in the stripped source for guard detection.
        start = re.search(rf"(function\s+{re.escape(fn)}\s*\(|const\s+{re.escape(fn)}\s*[:=])", stripped)
        body = stripped[start.start(): start.start() + 4000] if start else ""
        for m in JSDOC_EXAMPLE.finditer(source):
            call, want = m.group(1).strip(), m.group(2).strip().rstrip(";")
            if not call.startswith(fn + "(") or count >= max_per_function:
                continue
            out.append(Proposal(
                name=f"{fn} documented example {count + 1}",
                description=f"JSDoc @example for {fn}.", target=f"{rel}#{fn}", target_file=rel, category="regression",
                expected_behaviour=f"`{call}` returns `{want}` as documented in JSDoc.",
                code=(f"// Generated by TestPilot AI — review before approving.\nimport {{ {fn} }} from '{import_path}';\n\n"
                      f"it('{fn} documented example {count + 1}', () => {{\n  expect({call}).toEqual({want});\n}});\n"),
                rationale="Expected value is copied verbatim from the JSDoc @example.",
                strategy="example", source_files=[rel]))
            count += 1
        for m in list(GUARD.finditer(body)) + list(EMPTY_GUARD.finditer(body)):
            if count >= max_per_function:
                break
            if m.re is GUARD:
                param, op, lit, exc = m.group(1), m.group(2), m.group(3), m.group(4)
                if param not in params:
                    continue
                num = float(lit) if "." in lit else int(lit)
                step = 1 if isinstance(num, int) else 0.5
                val = {"===": num, "==": num, "<": num - step, "<=": num, ">": num + step, ">=": num}[op]
                why = f"{param} {op} {lit}"
            else:
                param, exc = m.group(2), m.group(3)
                if param not in params:
                    continue
                val, why = "[]", f"{param} is empty"
            args = ", ".join(str(val) if p == param else _placeholder(p) for p in params)
            title = f"{fn} throws {exc} when {why}"
            if any(p.name == title for p in out):
                continue
            out.append(Proposal(
                name=title, description=title + ".", target=f"{rel}#{fn}", target_file=rel,
                category="input-validation",
                expected_behaviour=f"`{fn}({args})` throws {exc}.",
                code=(f"// Generated by TestPilot AI — review before approving.\nimport {{ {fn} }} from '{import_path}';\n\n"
                      f"it('{title}', () => {{\n  expect(() => {fn}({args})).toThrow({exc if exc != 'Error' else ''});\n}});\n"),
                rationale=f"The source explicitly throws {exc} when `{why}`. Other arguments are placeholders — "
                          "verify they are valid.",
                strategy="guard", source_files=[rel]))
            count += 1
    return out


def validate_js_test(code: str) -> dict:
    stripped = strip_comments_and_strings(code)
    balanced = stripped.count("{") == stripped.count("}") and stripped.count("(") == stripped.count(")")
    return {"syntax_ok": balanced, "has_tests": bool(re.search(r"\b(it|test)\s*\(", code)),
            "forbidden_calls": ["eval"] if re.search(r"\beval\s*\(", stripped) else [],
            "check": "bracket balance (heuristic; full parsing happens at execution)"}
